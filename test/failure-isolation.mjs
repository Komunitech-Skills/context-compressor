  for(const dir of [main,second,blocked])mkdirSync(dir);
  writeFileSync(join(blocked,'memory'),'cannot create directory');
  entry.register({pluginConfig:{workspaceByAgent:{main,second,blocked},maxLedgerBytes:100},config:{},logger:{info(){},warn(){}},registerAgentToolResultMiddleware(fn){middleware=fn},on(n,fn){hooks[n]=fn}});
