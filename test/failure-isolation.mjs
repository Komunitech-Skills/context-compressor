  assert(!existsSync(join(main,'memory/cache/tee')));
  const tee=join(second,'memory/cache/tee'),file=join(tee,readdirSync(tee)[0]);
  assert.equal(readFileSync(file,'utf8'),text);assert.equal(statSync(file).mode&0o777,0o600);
  middleware(event,{agentId:'second'});assert(existsSync(join(second,'memory/cache/stats.jsonl.1')));
